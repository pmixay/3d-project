def _font(run, bold=False, italic=False):
    run.font.name = FONT
    run.font.size = Pt(12)
    run.bold = bold
    run.italic = italic
    r = run._element.get_or_add_rPr()
    f = r.find(qn("w:rFonts"))
    if f is None:
        f = OxmlElement("w:rFonts")
        r.append(f)
    for a in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        f.set(qn(a), FONT)
    return run


def para(text="", bold=False, align=None, indent=True, after=3, before=0, keep=False):
    p = doc.add_paragraph()
    if not indent:
        p.paragraph_format.first_line_indent = Cm(0)
    if align is not None:
        p.alignment = align
    p.paragraph_format.space_after = Pt(after)
    p.paragraph_format.space_before = Pt(before)
    if keep:
        p.paragraph_format.keep_with_next = True
    _rich(p, text, bold)
    return p


def _rich(p, text, bold=False):
    """**bold** fragments inside text."""
    parts = text.split("**")
    for i, chunk in enumerate(parts):
        if chunk:
            _font(p.add_run(chunk), bold=bold or i % 2 == 1)


def h(text):
    return para(text, bold=True, indent=False, before=6, after=3, keep=True)


def bullet(text):
    p = doc.add_paragraph(style="List Bullet")
    p.paragraph_format.first_line_indent = Cm(0)
    p.paragraph_format.space_after = Pt(1)
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    _rich(p, text)
    return p


def hyperlink(p, url, text):
    rid = p.part.relate_to(url, "http://schemas.openxmlformats.org/officeDocument/2006/relationships/hyperlink", is_external=True)
    hl = OxmlElement("w:hyperlink")
    hl.set(qn("r:id"), rid)
    r = OxmlElement("w:r")
    rp = OxmlElement("w:rPr")
    fonts = OxmlElement("w:rFonts")
    for a in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        fonts.set(qn(a), FONT)
    rp.append(fonts)
    sz = OxmlElement("w:sz")
    sz.set(qn("w:val"), "24")
    rp.append(sz)
    c = OxmlElement("w:color")
    c.set(qn("w:val"), "1F5FA8")
    rp.append(c)
    u = OxmlElement("w:u")
    u.set(qn("w:val"), "single")
    rp.append(u)
    r.append(rp)
    t = OxmlElement("w:t")
    t.text = text
    t.set(qn("xml:space"), "preserve")
    r.append(t)
    hl.append(r)
    p._p.append(hl)


def table(rows, widths, header=True, bold_last=False, num_col=None):
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    for j, w in enumerate(widths):
        t.columns[j].width = Cm(w)
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            cell = t.cell(i, j)
            cell.width = Cm(widths[j])
            p = cell.paragraphs[0]
            p.paragraph_format.first_line_indent = Cm(0)
            p.paragraph_format.space_after = Pt(0)
            p.alignment = WD_ALIGN_PARAGRAPH.RIGHT if (j == num_col and i > 0) else WD_ALIGN_PARAGRAPH.LEFT
            _font(p.add_run(val), bold=(header and i == 0) or (bold_last and i == len(rows) - 1))
    doc.add_paragraph().paragraph_format.space_after = Pt(0)
    return t


